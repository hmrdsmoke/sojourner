/// Haiola's block classes that carry verse text — the HTML twin of
/// `BlockKind::is_verse_flow`. `qs` (Selah) is its own div in HTML but an
/// inline run in USFM; either way it belongs to the verse it follows.
const HTML_FLOW_CLASSES: [&str; 12] = ["p", "m", "pi", "pc", "mi", "nb", "li", "q", "q2", "q3", "b", "qs"];

/// Decode the few entities Haiola emits. Anything unknown is left as written
/// so it shows up as a difference rather than vanishing.
fn decode_entities(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut rest = s;
    while let Some(amp) = rest.find('&') {
        out.push_str(&rest[..amp]);
        let tail = &rest[amp..];
        let Some(semi) = tail.find(';') else {
            out.push_str(tail);
            return out;
        };
        let entity = &tail[1..semi];
        let decoded: Option<char> = match entity {
            "amp" => Some('&'),
            "lt" => Some('<'),
            "gt" => Some('>'),
            "quot" => Some('"'),
            "apos" => Some('\''),
            "nbsp" => Some('\u{a0}'),
            e if e.starts_with("#x") || e.starts_with("#X") => {
                u32::from_str_radix(&e[2..], 16).ok().and_then(char::from_u32)
            }
            e if e.starts_with('#') => e[1..].parse::<u32>().ok().and_then(char::from_u32),
            _ => None,
        };
        match decoded {
            Some(c) => out.push(c),
            None => out.push_str(&tail[..=semi]),
        }
        rest = &tail[semi + 1..];
    }
    out.push_str(rest);
    out
}

/// Remove every footnote / cross-reference caller — `<a href="#FN…"
/// class="notemark">†<span class="popup">…</span></a>` — as a whole element.
/// The popup carries the note text (and, for cross-references, links), so a
/// plain tag-strip would leak note text into the verse. Nested `<a>` tags
/// inside the popup are counted so the right `</a>` closes the caller.
fn strip_note_callers(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut rest = s;
    loop {
        // The next anchor that is a note caller.
        let mut search = rest;
        let mut found: Option<usize> = None;
        while let Some(at) = search.find("<a ") {
            let base = rest.len() - search.len() + at;
            let tag_end = rest[base..].find('>').expect("unterminated <a> tag") + base;
            if rest[base..tag_end].contains("class=\"notemark\"") {
                found = Some(base);
                break;
            }
            search = &rest[base + 3..];
        }
        let Some(open) = found else {
            out.push_str(rest);
            return out;
        };
        out.push_str(&rest[..open]);

        // Find the matching </a>, counting nested anchors.
        let mut depth = 0i32;
        let mut i = open;
        loop {
            let next_open = rest[i..].find("<a ").map(|x| x + i);
            let next_close = rest[i..].find("</a>").map(|x| x + i);
            match (next_open, next_close) {
                (Some(o), Some(c)) if o < c => {
                    depth += 1;
                    i = o + 3;
                }
                (_, Some(c)) => {
                    depth -= 1;
                    i = c + 4;
                    if depth == 0 {
                        break;
                    }
                }
                _ => panic!("unterminated note caller"),
            }
        }
        rest = &rest[i..];
    }
}

/// Drop every inline tag and decode entities. Inline tags (`<span class='wj'>`,
/// `<span class='bk'>`…) sit inside the text with no spacing of their own —
/// `Yahweh</span>,` is "Yahweh," — so they must vanish, not become spaces.
/// Block boundaries are handled by the caller. A `<br>` is the one tag that
/// does mean a break, so it becomes a space.
fn html_text(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    let mut rest = s;
    while let Some(lt) = rest.find('<') {
        out.push_str(&rest[..lt]);
        match rest[lt..].find('>') {
            Some(gt) => {
                if rest[lt..lt + gt].starts_with("<br") {
                    out.push(' ');
                }
                rest = &rest[lt + gt + 1..];
            }
            None => rest = "",
        }
    }
    out.push_str(rest);
    decode_entities(&out)
}

/// The verses of one chapter page, keyed by verse number, as normalized plain
/// text — built the same way `plain_verses` builds ours: walk the blocks in
/// order, keep only verse-flow blocks, start a new verse at each verse span,
/// and join a verse's pieces across blocks with a space.
fn html_chapter_verses(page: &str) -> BTreeMap<u32, String> {
    let start = page.find("<div class=\"main\">").expect("no main div") + "<div class=\"main\">".len();
    let body = &page[start..];
    let end = body
        .find("<div class=\"footnote\">")
        .or_else(|| body.find("<div class=\"copyright\">"))
        .expect("no end of main");
    let main = strip_note_callers(&body[..end]);

    let mut verses: BTreeMap<u32, String> = BTreeMap::new();
    let mut current: Option<u32> = None;
    let mut rest = main.as_str();

    while let Some(at) = rest.find("<div class='") {
        let after = &rest[at + "<div class='".len()..];
        let class_end = after.find('\'').expect("unterminated class");
        let class = &after[..class_end];
        let body_start = after[class_end..].find('>').expect("unterminated div") + class_end + 1;
        let body = &after[body_start..];
        let body_end = body.find("</div>").expect("unterminated block div");
        let inner = &body[..body_end];
        rest = &body[body_end + "</div>".len()..];

        if !HTML_FLOW_CLASSES.contains(&class) {
            continue;
        }

        let mut piece = inner;
        loop {
            const VERSE: &str = "<span class=\"verse\" id=\"V";
            let text_end = piece.find(VERSE).unwrap_or(piece.len());
            if let Some(n) = current {
                let text = html_text(&piece[..text_end]);
                if !text.trim().is_empty() {
                    let verse = verses.get_mut(&n).expect("current verse exists");
                    verse.push(' ');
                    verse.push_str(&text);
                }
            }
            if text_end == piece.len() {
                break;
            }
            let num_start = text_end + VERSE.len();
            let num_end = piece[num_start..].find('"').expect("unterminated verse id") + num_start;
            let n: u32 = piece[num_start..num_end].parse().expect("verse id is a number");
            let span_end = piece[num_end..].find("</span>").expect("unterminated verse span") + num_end + "</span>".len();
            assert!(verses.insert(n, String::new()).is_none(), "verse {n} appears twice in one chapter");
            current = Some(n);
            piece = &piece[span_end..];
        }
    }

    verses.into_iter().map(|(n, t)| (n, comparable(&t))).collect()
}

/// What the word-for-word comparison deliberately ignores — applied to BOTH
/// sides, so neither text is ever adjusted to fit the other:
///
/// * whitespace between two adjacent quotation marks (`’”`, `“‘`). The
///   source itself is inconsistent here (three verses write `’ ”`, 865 write
///   `’”`), and the renderer normalizes every case to a non-breaking space;
/// * whitespace on either side of an em-dash. The renderer sets a `\qs`
///   (Selah) as its own block, which puts a space after the dash in
///   `Lord—Selah—` (Psalm 68:32) where the source has none.
///
/// Words, punctuation and their order are compared exactly.
fn comparable(s: &str) -> String {
    const QUOTES: [char; 4] = ['\u{201c}', '\u{201d}', '\u{2018}', '\u{2019}'];
    let n = normalized(s);
    let chars: Vec<char> = n.chars().collect();
    let mut out = String::with_capacity(n.len());
    for (i, &c) in chars.iter().enumerate() {
        if c == ' ' && i > 0 && i + 1 < chars.len() {
            let (prev, next) = (chars[i - 1], chars[i + 1]);
            if QUOTES.contains(&prev) && QUOTES.contains(&next) {
                continue;
            }
            if prev == '\u{2014}' || next == '\u{2014}' {
                continue;
            }
        }
        out.push(c);
    }
    out
}

#[test]
fn html_witness_matches_word_for_word() {
    let path = Path::new(env!("CARGO_MANIFEST_DIR")).join("assets/eng-web_html.zip");
    if !path.is_file() {
        eprintln!("publisher HTML not present at {}; skipping", path.display());
        return;
    }
    let bytes = std::fs::read(&path).expect("read HTML zip");
    let mut archive = zip::ZipArchive::new(std::io::Cursor::new(bytes)).expect("open HTML zip");

    // (book code, chapter) → page. Chapter pages are named like ACT08.htm,
    // PSA119.htm, 1CH01.htm; book intros (ACT.htm) and the rest are skipped.
    let mut pages: BTreeMap<(String, u32), String> = BTreeMap::new();
    for i in 0..archive.len() {
        let mut entry = archive.by_index(i).expect("zip entry");
        let name = entry.name().rsplit('/').next().unwrap_or("").to_string();
        let Some(stem) = name.strip_suffix(".htm") else { continue };
        if stem.len() < 5 || !stem.is_char_boundary(3) {
            continue;
        }
        let (code, digits) = stem.split_at(3);
        let Ok(chapter) = digits.parse::<u32>() else { continue };
        let mut page = String::new();
        std::io::Read::read_to_string(&mut entry, &mut page).expect("read page");
        pages.insert((code.to_string(), chapter), page);
    }

    let bible = text::usfm::load_bundled().unwrap_or_else(|e| panic!("parse failed: {e}"));
    let mut compared = 0usize;
    let mut problems: Vec<String> = Vec::new();

    for book in &bible.books {
        for chapter in &book.chapters {
            let key = (book.code.clone(), chapter.number);
            let Some(page) = pages.get(&key) else {
                problems.push(format!("{} {}: no page in the HTML zip", book.code, chapter.number));
                continue;
            };
            let theirs = html_chapter_verses(page);

            let mut ours: BTreeMap<u32, String> = BTreeMap::new();
            for (ch, number, plain) in text::plain_verses(book) {
                if ch == chapter.number {
                    ours.insert(number.start, comparable(&plain));
                }
            }

            for n in ours.keys() {
                if !theirs.contains_key(n) {
                    problems.push(format!("{} {}:{n} — in ours, not in the publisher's HTML", book.code, chapter.number));
                }
            }
            for n in theirs.keys() {
                if !ours.contains_key(n) {
                    problems.push(format!("{} {}:{n} — in the publisher's HTML, not in ours", book.code, chapter.number));
                }
            }
            for (n, a) in &ours {
                if let Some(b) = theirs.get(n) {
                    compared += 1;
                    if a != b {
                        problems.push(format!("{} {}:{n}\n    ours: {a}\n    html: {b}", book.code, chapter.number));
                    }
                }
            }
        }
    }

    eprintln!("publisher HTML: {compared} verses compared, {} differences", problems.len());
    for p in problems.iter().take(40) {
        eprintln!("  {p}");
    }
    assert_eq!(compared, 38058, "verses compared against the publisher's HTML");
    assert!(problems.is_empty(), "{} difference(s) from the publisher's own rendering (listed above)", problems.len());
}
