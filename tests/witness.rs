//! The proof that Sojourner's text is the publisher's text.
//!
//! `cargo test` runs three checks against the zip compiled into the binary:
//!
//! 1. A census. Every count that was measured on the raw files with grep
//!    when the parser was designed (see assets/SOURCES.md) is asserted here
//!    against the parsed model: books, chapters, verse markers per section,
//!    footnotes, cross-references, word tags, poetry lines… If the parser
//!    ever drops or duplicates anything, a number moves and this fails.
//!
//! 2. An independent witness. If `assets/web-source/json` is present (a
//!    separate JSON conversion of the WEB by a third party, not shipped), the
//!    66 Protestant books are compared verse by verse. The witness turned out
//!    to be a *pre-2020* edition of the text: same 31,103 verses, but the
//!    publisher's later language updates ("in the earth" → "on the earth",
//!    "I come quickly" → "I am coming soon") show up as differences. So this
//!    test asserts what the witness can prove — that our verse structure is
//!    identical — and reports the wording drift without failing on it. The
//!    word-for-word proof is check 3.
//!
//! 3. The publisher's own rendering. If `assets/eng-web_html.zip` is present
//!    (the HTML edition of the WEB, generated by the publisher's tool Haiola
//!    from the same source files as the USFM zip, on the same day), every
//!    verse of every book — Old Testament, Deuterocanon and New Testament,
//!    38,058 verse markers — is compared word for word against our parse.
//!    Same source, same edition, a different program reading it: this has to
//!    come back at zero differences, and any difference is ours to explain.

use std::collections::{BTreeMap, BTreeSet};
use std::path::Path;

use sojourner::text::{self, *};

// ────────────────────────────────────────────────────────────────────────────
// 1. Census
// ────────────────────────────────────────────────────────────────────────────

#[derive(Default, Debug)]
struct Census {
    books: usize,
    chapters: usize,
    verse_markers: usize,
    verses_old: usize,
    verses_deutero: usize,
    verses_new: usize,
    bridged: usize,
    footnotes: usize,
    cross_refs: usize,
    word_tags: usize,
    paragraphs: usize,
    poetry_lines: usize,
    blanks: usize,
    superscriptions: usize,
    non_empty_blanks: usize,
}

fn count_blocks(census: &mut Census, section: Section, blocks: &[Block]) {
    for block in blocks {
        match block.kind {
            BlockKind::Paragraph => census.paragraphs += 1,
            BlockKind::Poetry(_) => census.poetry_lines += 1,
            BlockKind::Blank => {
                census.blanks += 1;
                if !block.content.is_empty() {
                    census.non_empty_blanks += 1;
                }
            }
            BlockKind::Superscription => census.superscriptions += 1,
            _ => {}
        }
        for inline in &block.content {
            match inline {
                Inline::Verse(n) => {
                    census.verse_markers += 1;
                    if n.end != n.start {
                        census.bridged += 1;
                    }
                    match section {
                        Section::OldTestament => census.verses_old += 1,
                        Section::Deuterocanon => census.verses_deutero += 1,
                        Section::NewTestament => census.verses_new += 1,
                        Section::FrontMatter | Section::Glossary => {}
                    }
                }
                Inline::Text(run) => census.word_tags += run.words.len(),
                Inline::Footnote(note) => {
                    census.footnotes += 1;
                    for run in &note.content {
                        census.word_tags += run.words.len();
                    }
                }
                Inline::CrossRef(_) => census.cross_refs += 1,
            }
        }
    }
}

fn census(bible: &Bible) -> Census {
    let mut c = Census::default();
    for book in &bible.books {
        c.books += 1;
        c.chapters += book.chapters.len();
        count_blocks(&mut c, book.section, &book.intro);
        for chapter in &book.chapters {
            count_blocks(&mut c, book.section, &chapter.blocks);
        }
    }
    c
}

#[test]
fn census_matches_the_publishers_files() {
    let bible = text::usfm::load_bundled().unwrap_or_else(|e| panic!("parse failed: {e}"));
    let c = census(&bible);
    eprintln!("{c:#?}");

    // Files: front matter + 39 OT + 15 Deuterocanon + 27 NT + glossary.
    assert_eq!(c.books, 83, "books");
    assert_eq!(c.chapters, 1402, "chapters (\\c)");

    // Verse markers (\v). A bridged verse like \v 15-16 is one marker.
    assert_eq!(c.verse_markers, 38058, "verse markers (\\v)");
    assert_eq!(c.verses_old, 23145, "Old Testament verse markers");
    assert_eq!(c.verses_deutero, 6955, "Deuterocanon verse markers");
    assert_eq!(c.verses_new, 7958, "New Testament verse markers");
    assert_eq!(c.verses_old + c.verses_new, 31103, "Protestant canon verse markers");
    assert_eq!(c.bridged, 6, "bridged verse numbers (\\v N-M)");

    assert_eq!(c.footnotes, 1855, "footnotes (\\f)");
    assert_eq!(c.cross_refs, 363, "cross-references (\\x)");
    assert_eq!(c.word_tags, 677_690, "word tags (\\w + \\+w)");

    assert_eq!(c.paragraphs, 9254, "paragraphs (\\p)");
    assert_eq!(c.poetry_lines, 10094 + 13237 + 7, "poetry lines (\\q1 + \\q2 + \\q3)");
    assert_eq!(c.blanks, 1070, "stanza breaks (\\b)");
    assert_eq!(c.non_empty_blanks, 0, "\\b blocks must be empty");
    assert_eq!(c.superscriptions, 139, "Psalm superscriptions (\\d)");

    // The publisher's own bookkeeping: every file names its book, and every
    // book but the front matter and glossary has chapters.
    for book in &bible.books {
        let chapterless = matches!(book.section, Section::FrontMatter | Section::Glossary);
        assert_eq!(book.chapters.is_empty(), chapterless, "{}: chapters", book.file);
        if !chapterless {
            assert!(!book.names.short.is_empty(), "{}: no \\toc2 name", book.file);
        }
    }
}

/// The only verses in the Protestant canon with no text are the ones the
/// translators footnoted: verses found in the Textus Receptus but not the
/// Majority Text, and the Romans doxology (moved after 14:23). If this set
/// ever grows, a verse has gone missing.
#[test]
fn only_the_footnoted_verses_are_empty() {
    let bible = text::usfm::load_bundled().unwrap_or_else(|e| panic!("parse failed: {e}"));
    let mut empty = BTreeSet::new();
    for book in &bible.books {
        if !matches!(book.section, Section::OldTestament | Section::NewTestament) {
            continue;
        }
        for (chapter, number, plain) in text::plain_verses(book) {
            if plain.trim().is_empty() {
                empty.insert(format!("{} {chapter}:{}", book.code, number.start));
            }
        }
    }
    let expected: BTreeSet<String> = ["LUK 17:36", "ACT 8:37", "ACT 15:34", "ACT 24:7", "ROM 16:25"]
        .iter()
        .map(|s| s.to_string())
        .collect();
    assert_eq!(empty, expected);
}

